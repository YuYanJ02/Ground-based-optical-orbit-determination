function cmap = cmapInferno(n)
%CMAPINFERNO Matplotlib inferno 配色
    if nargin < 1
        n = 256;
    end
    anchors = [ ...
        0.001462, 0.000466, 0.013866; ...
        0.087411, 0.044556, 0.224228; ...
        0.258234, 0.038571, 0.406324; ...
        0.416331, 0.090902, 0.432263; ...
        0.579348, 0.148031, 0.404411; ...
        0.735683, 0.215906, 0.330245; ...
        0.865006, 0.316915, 0.226055; ...
        0.948906, 0.488189, 0.104912; ...
        0.987053, 0.645320, 0.039886; ...
        0.988362, 0.998364, 0.644924];
    t = linspace(0, 1, size(anchors, 1));
    q = linspace(0, 1, n);
    cmap = [ ...
        interp1(t, anchors(:, 1), q)', ...
        interp1(t, anchors(:, 2), q)', ...
        interp1(t, anchors(:, 3), q)'];
end
