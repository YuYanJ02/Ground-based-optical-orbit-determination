               '13:58:06.1031'};

% 2. 转换数据为十进制小时/度
RA = zeros(size(raw_W_str));
Dec = zeros(size(raw_Dec_str));

for i = 1:length(raw_W_str)
    % 转换西经 HMS 为十进制小时，并用 24 减去得到赤经
    parts_w = sscanf(raw_W_str{i}, '%f:%f:%f');
    w_hours = parts_w(1) + parts_w(2)/60 + parts_w(3)/3600;
    RA(i) = 24 - w_hours;
    
    % 转换赤纬 HMS 为十进制角度 (南纬为负)
    parts_d = sscanf(raw_Dec_str{i}, '%f:%f:%f');
    Dec(i) = -(parts_d(1) + parts_d(2)/60 + parts_d(3)/3600);
end

% 3. 绘图
figure('Color', 'w');
plot(RA, Dec, '-ro', 'LineWidth', 1.5, 'MarkerSize', 4, 'MarkerFaceColor', 'r');
grid on; hold on;

% 设置坐标轴范围
% 赤经 18H30M = 18.5, 18H45M = 18.75
% 赤纬 -10DMS = -10, -15DMS = -15
xlim([18.5, 18.75]);
ylim([-15, -10]);

% 习惯上天文图中赤经轴是反向的（从右向左增加）
set(gca, 'XDir', 'reverse');

% 格式化标签
xlabel('Right Ascension (Hours)');
ylabel('Declination (Degrees)');
title('Trajectory Plot (2026-04-06)');

% 添加起始和结束点标注
