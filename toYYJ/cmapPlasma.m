function cmap = cmapPlasma(n)
%CMAPPLASMA Matplotlib plasma 配色
    if nargin < 1
        n = 256;
    end
    anchors = [ ...
        0.050383, 0.029803, 0.527975; ...
        0.186213, 0.018982, 0.587949; ...
        0.287076, 0.010100, 0.627295; ...
        0.381047, 0.001814, 0.653068; ...
        0.471457, 0.005678, 0.659897; ...
        0.541173, 0.025833, 0.638316; ...
        0.613267, 0.074444, 0.582659; ...
        0.692840, 0.144907, 0.502284; ...
        0.781591, 0.246676, 0.399259; ...
        0.868751, 0.375866, 0.279711; ...
        0.940015, 0.975158, 0.131326];
    t = linspace(0, 1, size(anchors, 1));
    q = linspace(0, 1, n);
    cmap = [ ...
        interp1(t, anchors(:, 1), q)', ...
        interp1(t, anchors(:, 2), q)', ...
        interp1(t, anchors(:, 3), q)'];
end
